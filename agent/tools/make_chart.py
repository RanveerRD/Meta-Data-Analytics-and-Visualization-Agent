"""Draw a bar or line chart from a recorded query's rows.

The model never writes plotting code and never supplies data points:
every value comes from a query already run and stored in the record.
The output filename is generated by code; the model never sees a path.
"""

from __future__ import annotations

import json
import re
import textwrap
from decimal import Decimal
from numbers import Real
from pathlib import Path
from typing import Any

import matplotlib

matplotlib.use("Agg")

import matplotlib.pyplot as plt  # noqa: E402

from agent.numbers import extract_numbers, match_recorded, normalize_token

