_MAX_POINTS = 50
_MIN_POINTS = 2
_MAX_WIDTH = 16.0
_ROTS = [0, 45, 90]
_EPS_PX = 1.0

REPO_ROOT = Path(__file__).resolve().parent.parent.parent


def _display_path(path: str | Path) -> str:
    """Path relative to the project root, like the Record line."""
    try:
        return str(Path(path).relative_to(REPO_ROOT))
    except ValueError:
        return str(path)


_MONTH_RE = re.compile(r"^(\d{4})-(0[1-9]|1[0-2])$")
_YEAR_RE = re.compile(r"^(\d{4})$")


def _month_index(year: int, month: int) -> int:
    return year * 12 + (month - 1)


def _missing_periods(x_labels: list[str]) -> list[str]:
    """Periods absent between the first and last x value, if x is uniform.

    Returns YYYY-MM gaps when every x is monthly, YYYY gaps when every x
    is yearly, else []. A uniform date series is also the signal to plot
    in chronological order.
    """
    months: list[int] = []
    for label in x_labels:
        match = _MONTH_RE.match(label)
        if not match:
            break
        months.append(_month_index(int(match.group(1)), int(match.group(2))))
    else:
        if months:
            return _gaps(months, lambda i: f"{i // 12:04d}-{i % 12 + 1:02d}")
    years: list[int] = []
    for label in x_labels:
        match = _YEAR_RE.match(label)
        if not match:
            return []
        years.append(int(match.group(1)))
    if not years:
        return []
    return _gaps(years, lambda y: f"{y:04d}")


def _gaps(idxs: list[int], fmt: Any) -> list[str]:
    present = set(idxs)
    return [fmt(i) for i in range(min(idxs), max(idxs) + 1) if i not in present]


def _is_date_series(x_labels: list[str]) -> bool:
    """True when every x is monthly (YYYY-MM) or every x is yearly (YYYY)."""
    return bool(x_labels) and (
        all(_MONTH_RE.match(x) for x in x_labels)
        or all(_YEAR_RE.match(x) for x in x_labels)
    )


def _fill_gaps(
    labels: list[str], values: list[float], missing: list[str]
) -> tuple[list[str], list[float]]:
    """Chronological series with NaN inserted at missing periods.

    Lines break at NaN; NaN bars draw nothing, leaving the empty slot.
    Uniform date series are sorted chronologically even with no gaps.
    """
    if not missing and not _is_date_series(labels):
        return labels, values
    present = dict(zip(labels, values))
    full = sorted(set(labels) | set(missing))
    return full, [present.get(label, float("nan")) for label in full]


def _chart_note(missing: list[str]) -> str:
    listed = missing if len(missing) <= 6 else missing[:6] + [f"and {len(missing) - 6} more"]
    return f"no data for {', '.join(listed)} (not drawn)"


def _refuse(reason: str) -> str:
    return json.dumps({"error": reason})


def _check_title(title: str, cells: list[Any], points: int) -> str | None:
    """Every number in the title must be the point count or a recorded value.

    Years (1900-2100) and dates pass free: extract_numbers masks dates
    and normalize_token returns None for years.
    """
    bad: list[str] = []
    for token in extract_numbers(title):
        if normalize_token(token) is None:
            continue
        try:
            is_count = Decimal(normalize_token(token) or "") == points
        except Exception:
            is_count = False
        if not is_count and not match_recorded(token, cells):
            bad.append(token)
    if bad:
        return (
            f"title number(s) {', '.join(bad)} are not in the query rows; "
            "use only numbers from the query result (years and dates are fine, "
            "and an integer equal to the point count is allowed)."
        )
    return None


def _base_width(n: int) -> float:
    return min(max(6.4, 0.45 * n), _MAX_WIDTH)


def _apply_ticks(ax: Any, labels: list[str], rot: int, step: int) -> None:
    """Show every step-th label, always keeping the first and the last."""
    n = len(labels)
    idx = sorted(set(range(0, n, step)) | ({n - 1} if n else set()))
    ax.set_xticks(list(idx), [labels[i] for i in idx])
    for text in ax.get_xticklabels():
        text.set_rotation(rot)
        text.set_ha("right" if rot else "center")


def _boxes_overlap(a: Any, b: Any) -> bool:
    return a.padded(_EPS_PX).overlaps(b.padded(_EPS_PX))


def _inside(fig: Any, box: Any) -> bool:
    fb = fig.bbox
    return (
        box.x0 >= fb.x0 - _EPS_PX
        and box.y0 >= fb.y0 - _EPS_PX
        and box.x1 <= fb.x1 + _EPS_PX
        and box.y1 <= fb.y1 + _EPS_PX
    )


def _ticks_clean(fig: Any, ax: Any) -> bool:
    fig.tight_layout()
    fig.canvas.draw()
    renderer = fig.canvas.get_renderer()
    boxes = [
        t.get_window_extent(renderer)
        for t in ax.get_xticklabels()
        if t.get_visible()
    ]
    if not boxes:
        return False
    if any(not _inside(fig, box) for box in boxes):
        return False
    return not any(
        _boxes_overlap(a, b)
        for i, a in enumerate(boxes)
        for b in boxes[i + 1:]
    )


def _ladder(chart_type: str, n: int) -> list[tuple[int, float, int]]:
    """Deterministic escalation: rotation, then widening or thinning.

    Bar charts widen up to the cap before thinning (a hidden tick hides
    which bar a label belongs to, so thinning is the last resort); line
    charts thin before widening. The first and last labels always stay.
    """
    base = _base_width(n)
    widths = sorted({base, min(base * 1.6, _MAX_WIDTH), _MAX_WIDTH})
    thin = list(range(2, n + 1))
    if chart_type == "bar":
        combos = [(r, w, 1) for r in _ROTS for w in widths]
        combos += [(90, _MAX_WIDTH, s) for s in thin]
    else:
        combos = [(r, base, 1) for r in _ROTS]
        combos += [(90, base, s) for s in thin]
        combos += [(90, w, 1) for w in widths[1:]]
        combos += [(90, _MAX_WIDTH, s) for s in thin]
    return combos


def _drop_overlapping_bar_values(fig: Any, ax: Any) -> None:
    """Remove bar value labels if any overlap or leave the figure."""
    texts = [t for t in ax.texts if t.get_visible() and t.get_text().strip()]
    if not texts:
        return
    fig.canvas.draw()
    renderer = fig.canvas.get_renderer()
    boxes = [t.get_window_extent(renderer) for t in texts]
    bad = any(not _inside(fig, box) for box in boxes) or any(
        _boxes_overlap(a, b)
        for i, a in enumerate(boxes)
        for b in boxes[i + 1:]
    )
    if bad:
        for text in texts:
            text.remove()


def _render_figure(
    raw_labels: list[str],
    values: list[float],
    chart_type: str,
    title: str,
    x_column: str,
    y_column: str,
) -> tuple[Any, Any]:
    """Draw the chart with the first non-overlapping label layout.

    Returns (fig, ax); the caller saves and closes. Deterministic: the
    same inputs always walk the same ladder and stop at the same layout.
    """
    labels = [textwrap.fill(label, 15) for label in raw_labels]
    n = len(labels)
    fig, ax = plt.subplots(figsize=(_base_width(n), 4.8))
    if chart_type == "bar":
        ax.bar(range(n), values)
        ax.set_ylim(bottom=0)
        ax.bar_label(
            ax.containers[0],
            fmt=lambda v: "" if v != v else f"{v:,.2f}",
            padding=2,
            fontsize=8,
        )
    else:
        ax.plot(range(n), values, marker="o")
    ax.set_xlabel(x_column)
    ax.set_ylabel(y_column)
    ax.set_title(title)
    for rot, width, step in _ladder(chart_type, n):
        fig.set_size_inches(width, 4.8)
        _apply_ticks(ax, labels, rot, step)
        if _ticks_clean(fig, ax):
            break
    if chart_type == "bar":
        _drop_overlapping_bar_values(fig, ax)
    fig.tight_layout()
    fig.canvas.draw()
    return fig, ax


def run(ctx: Any, args: dict[str, Any]) -> str:
    record = ctx.record
    if record is None:
        return _refuse("make_chart is refused: call set_checklist first, then plan_action.")
    query_id = args["query_id"]
    query = next((q for q in record.queries if q["id"] == query_id), None)
    if query is None:
        if any(f["id"] == query_id for f in record.failed_queries):
            return _refuse(
                f"query {query_id!r} failed and has no citable result; "
                "run a new query with run_sql and chart that one."
            )
        return _refuse(
            f"unknown query {query_id!r}; run it first with run_sql, "
            "record a finding from it, then chart it."
        )
    if not any(f.get("query_id") == query_id for f in record.findings):
        return _refuse(
            f"query {query_id!r} has no recorded finding; "
            "record a finding from this query first."
        )
    if query.get("truncated"):
        return _refuse(
            f"query {query_id!r} was cut at 200 rows; aggregate or LIMIT in SQL, "
            "record a finding from the new query, then chart that one."
        )
    chart_type = args["chart_type"]
    if chart_type not in ("bar", "line"):
        return _refuse('chart_type must be "bar" or "line".')
    columns = list(query.get("columns", []))
    for key in ("x_column", "y_column"):
        if args[key] not in columns:
            return _refuse(
                f"{key} {args[key]!r} is not a column of {query_id}; "
                f"choose from: {', '.join(columns)}."
            )
    xi = columns.index(args["x_column"])
    yi = columns.index(args["y_column"])
    points: list[tuple[str, float]] = []
    skipped = 0
    for row in query.get("rows", []):
        raw_y = row[yi]
        if raw_y is None:
            skipped += 1
            continue
        if isinstance(raw_y, bool) or not isinstance(raw_y, (int, float, Decimal)):
            return _refuse(
                f"y column {args['y_column']!r} has a non-numeric value "
                f"{raw_y!r}; chart a numeric column instead."
            )
        points.append((str(row[xi]), float(raw_y)))
    if not (_MIN_POINTS <= len(points) <= _MAX_POINTS):
        return _refuse(
            f"query {query_id!r} gives {len(points)} plottable points; "
            "need 2 to 50. Aggregate or LIMIT in SQL and chart the new query."
        )
    cells = [v for row in query.get("rows", []) for v in row]
    title_error = _check_title(args["title"], cells, len(points))
    if title_error is not None:
        return _refuse(title_error)

    charts_dir = Path(ctx.runs_dir).parent / "charts"
    charts_dir.mkdir(parents=True, exist_ok=True)
    number = len(record.charts) + 1
    out = charts_dir / f"{record.run_id}-{number}.png"

    raw_labels = [label for label, _ in points]
    values = [value for _, value in points]
    missing = _missing_periods(raw_labels)
    note = _chart_note(missing) if missing else ""
    plot_labels, plot_values = _fill_gaps(raw_labels, values, missing)
    try:
        fig, ax = _render_figure(
            plot_labels, plot_values, chart_type,
            args["title"], args["x_column"], args["y_column"],
        )
        fig.savefig(out, dpi=150)
    finally:
        plt.close("all")
    entry = record.record_chart(
        query_id, chart_type, args["x_column"], args["y_column"],
        args["title"], _display_path(out), len(points), skipped, note,
    )
    description = (
        f"{chart_type} chart of {args['y_column']} by {args['x_column']}, "
        f"{len(points)} points"
        + (f" ({skipped} empty rows skipped)" if skipped else "")
    )
    return json.dumps(
        {"ok": True, "path": entry["path"], "description": description,
         "points": len(points), "chart_id": entry["id"]}
    )
